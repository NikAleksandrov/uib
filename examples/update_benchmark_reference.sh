set -eu

project_dir=$(CDPATH='' cd -- "$(dirname -- "$0")/.." && pwd)
output=${UIB_BENCH_OUTPUT:-/tmp/uib-benchmark-reference-$(date +%Y%m%d-%H%M%S)}
document=${UIB_BENCH_DOCUMENT:-$project_dir/docs/benchmark-results.md}
sync_document=${UIB_BENCH_SYNC_DOCUMENT:-$project_dir/docs/sync-async-benchmark.md}
candidate=$output/benchmark-reference.md
sync_candidate=$output/sync-async-reference.md
reuse=${UIB_BENCH_REUSE:-0}

mkdir -p "$output"
if [ "$reuse" != 1 ]; then
	"$project_dir/examples/benchmark_matrix.sh" "$output"
fi
"$project_dir/examples/benchmark_report.sh" "$output"

{
	printf '# Synchronous versus asynchronous UDP benchmark\n\n'
	printf 'Generated by `make benchmark-doc` on %s.\n\n' \
		"$(date -u '+%Y-%m-%d %H:%M:%S UTC')"
	printf -- '- Kernel: `%s`\n' "$(uname -sr)"
	printf -- '- CPUs available: `%s`\n' "$(getconf _NPROCESSORS_ONLN)"
	printf -- '- Iterations: `%s`\n' "${UIB_BENCH_ITERATIONS:-10000}"
	printf -- '- Message size: `%s` bytes\n' \
		"${UIB_BENCH_SIZE:-32768}"
	printf -- '- Window: `%s` operations\n\n' \
		"${UIB_BENCH_WINDOW:-64}"
	printf 'Both modes use the same UDP socket and io_uring RX worker; only '
	printf 'the TX submission path differs. Positive percentages mean the '
	printf 'asynchronous path improved.\n\n'
	awk '/^## Asynchronous UDP compared with synchronous UDP$/ { copy=1 }
	     copy && /^## / &&
	     $0 != "## Asynchronous UDP compared with synchronous UDP" { exit }
	     copy && !length($0) { blank=1; next }
	     copy {
		if (blank) {
			print "";
			blank=0;
		}
		print;
	     }' "$output/benchmark.md"
} >"$sync_candidate"
mv "$sync_candidate" "$sync_document"
printf 'Updated sync/async benchmark: %s\n' "$sync_document"

"$project_dir/examples/compare_benchmark_baseline.sh" "$document" "$output"

{
	printf '# UIB complete benchmark reference\n\n'
	printf 'Generated by `make benchmark-doc` on %s.\n\n' \
		"$(date -u '+%Y-%m-%d %H:%M:%S UTC')"
	printf -- '- Kernel: `%s`\n' "$(uname -sr)"
	printf -- '- CPUs available: `%s`\n' "$(getconf _NPROCESSORS_ONLN)"
	printf -- '- Iterations: `%s`\n' "${UIB_BENCH_ITERATIONS:-10000}"
	printf -- '- Message size: `%s` bytes\n' "${UIB_BENCH_SIZE:-32768}"
	printf -- '- Window: `%s` operations\n\n' "${UIB_BENCH_WINDOW:-64}"
	cat "$output/baseline-comparison.md"
	printf '\n\n'
	cat "$output/benchmark.md"
} >"$candidate"

mv "$candidate" "$document"
printf 'Updated benchmark reference: %s\n' "$document"
